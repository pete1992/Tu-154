			pitch_submode = 1
		elseif pitch_mode_main == 1 and (pitch_submode == 2 or pitch_submode == 3 or pitch_submode == 4) then 
			pitch_submode = 1
		end
	else 
		pitch_submode = 0
	end
	if reset_but then 
		roll_submode = 1
		if pitch_submode < 2 or pitch_submode > 4 then
			pitch_submode = 1
		end
	end
	if pitch_submode ~= 6 then
		TOGA_mode = false
	end
	pitch_wheel_last = putch_wheel
	if pitch_mode_main == 2 and (not isILS(get(freq_1)) or not land_prep or get(nav_gs_flag_1) == 1) and pitch_submode == 5 then 
