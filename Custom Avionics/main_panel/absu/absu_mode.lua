function update()
	thro_last_1 = get(tro_comm_1)
	thro_last_2 = get(tro_comm_2)
	thro_last_3 = get(tro_comm_3)
	set(autopilot_mode, 0)
local MASTER = get(ismaster) ~= 1	
if MASTER then	
	roll_mode_main = get(roll_main_mode)
